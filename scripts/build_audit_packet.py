    ("images_distinguishable", "四图可区分", "四张图的可见状态是否足以相互区分？"),
    ("text_supports_states", "文字涵盖状态", "有序食谱是否为四图均提供可对应的步骤或状态描述？"),
    ("alternative_orders", "存在合理替代对应／顺序", "是否存在多种合理的图→步骤对应或排序？请在备注说明图片标签及原因。"),
