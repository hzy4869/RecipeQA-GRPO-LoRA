"""Build a model-free, anonymous, offline RecipeQA input-audit packet.

Production CLI reads/writes only under /root/autodl-tmp. Each reviewer receives
their HTML, blank CSV, and assets/; do not distribute PRIVATE_mapping.json.
Human labels are never generated by this script.
"""

