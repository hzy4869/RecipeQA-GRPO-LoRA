def build_packet(
    manifest: Path, image_root: Path, output_dir: Path, *,
    allowed_root: Path = DATA_DISK, expected_count: int = 100,
) -> dict[str, Any]:
    """Create packet; custom allowed_root exists only for isolated local tests."""
    manifest = confined(manifest, allowed_root)
    image_root = confined(image_root, allowed_root)
    output_dir = confined(output_dir, allowed_root)
    if not manifest.is_file() or not image_root.is_dir():
        raise ValueError("Manifest file and image-root directory must already exist")
    from PIL import Image

    raw_manifest = manifest.read_bytes()
    manifest_sha = hashlib.sha256(raw_manifest).hexdigest()
    rows = [json.loads(line) for line in raw_manifest.splitlines() if line.strip()]
    if len(rows) != expected_count:
        raise ValueError(f"Expected {expected_count} audit questions; found {len(rows)}. No sampling/filtering is performed.")
    if len({row["recipe_id"] for row in rows}) != len(rows) or len({row["qid"] for row in rows}) != len(rows):
        raise ValueError("Audit manifest must have one question per distinct recipe")
    for row in rows:
        if len(row.get("image_paths_display", [])) != 4 or not row.get("steps"):
            raise ValueError("Every question must provide four display image paths and complete recipe steps")
    output_dir.mkdir(parents=True, exist_ok=True)
    metadata_path = confined(output_dir / "packet_manifest.json", allowed_root)
    if metadata_path.exists():
        previous = json.loads(metadata_path.read_text())
        if previous.get("source_manifest_sha256") != manifest_sha:
            raise ValueError("Output directory already belongs to a different manifest; use a new directory to preserve frozen IDs")
    assets = confined(output_dir / "assets", allowed_root)
    assets.mkdir(parents=True, exist_ok=True)
    entries, mappings, issues = [], [], []
    for index, row in enumerate(rows, 1):
        audit_id = f"R{index:03d}"
        entry = {"audit_id": audit_id, "steps": [
            {"title": step.get("title", ""), "body": step.get("body", "")}
            for step in row["steps"]
        ], "images": []}
        mappings.append({"audit_id": audit_id, "qid": row["qid"], "recipe_id": row["recipe_id"],
                         "presentation_id": row.get("presentation_id")})
        for label, relative in zip(LABELS, row["image_paths_display"]):
            asset_name = f"{audit_id.lower()}_{label.lower()}.jpg"
            asset_path = confined(assets / asset_name, allowed_root)
            source_error = None
            try:
                if not isinstance(relative, str) or Path(relative).is_absolute() or ".." in Path(relative).parts:
                    raise ValueError("Invalid or missing relative image path")
                source = confined(image_root / relative, image_root)
                # PIL creates a fresh RGB JPEG, preserving no source EXIF/name.
                with Image.open(source) as opened:
                    # Match the model input's Image.open(...).convert('RGB')
                    # orientation; do not silently introduce an EXIF transform.
                    image = opened.convert("RGB")
                    image.thumbnail((512, 512), Image.Resampling.LANCZOS)
                    temporary = confined(asset_path.with_name(asset_path.name + ".part"), allowed_root)
                    image.save(temporary, format="JPEG", quality=90, optimize=True)
                    temporary.replace(asset_path)
            except Exception as exc:
                source_error = type(exc).__name__
                issues.append({"audit_id": audit_id, "label": label, "error_class": source_error})
                if asset_path.exists():
                    asset_path.unlink()  # Never show a stale thumbnail as successful.
            entry["images"].append({"label": label, "asset": f"assets/{asset_name}" if source_error is None else None})
        entries.append(entry)
    audit_ids = [entry["audit_id"] for entry in entries]
    packet_hash = hashlib.sha256((manifest_sha + ":input-audit-packet-v1").encode()).hexdigest()
    for reviewer in ("reviewer_1", "reviewer_2"):
        atomic_text(confined(output_dir / f"{reviewer}.html", allowed_root), render_html(entries, reviewer, packet_hash))
        atomic_text(confined(output_dir / f"{reviewer}_blank.csv", allowed_root), blank_csv(audit_ids, reviewer))
    atomic_text(confined(output_dir / "PRIVATE_mapping.json", allowed_root), json.dumps({
        "not_for_reviewers": True, "purpose": "Join independently completed anonymous input audits back to the frozen manifest",
        "source_manifest_sha256": manifest_sha, "mapping": mappings,
    }, ensure_ascii=False, indent=2) + "\n")
    report = {
        "schema": "recipeqa-input-audit-packet-v1", "source_manifest_sha256": manifest_sha,
        "packet_hash": packet_hash, "questions": len(rows), "reviewers": 2,
        "max_thumbnail_dimensions": [512, 512], "thumbnails": len(rows) * 4 - len(issues),
        "technical_issues": issues,
        "human_labels": "NOT GENERATED: reviewer CSV decision fields are blank",
        "privacy": "Reviewer HTML/CSV/assets contain no source IDs, image filenames, target order, or model predictions; PRIVATE_mapping.json is investigator-only",
    }
    atomic_text(metadata_path, json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    atomic_text(confined(output_dir / "README.txt", allowed_root),
        "RecipeQA 输入可判定性独立审核包\n\n"
        "分别发给两名审核者：其 reviewer_1.html 或 reviewer_2.html、同名 _blank.csv，以及整个 assets 文件夹。\n"
        "请保留相对目录，然后用浏览器直接打开HTML。无需联网或启动服务器。点击图片可放大缩略图。\n"
        "先独立审核再讨论，不向审核者提供模型结果、另一人的标签或 PRIVATE_mapping.json。\n"
        "HTML会尝试在各自浏览器保存未完成填写；请定期导出CSV。也可直接编辑空白CSV。\n"
        "CSV字段取 yes/no/unclear，notes 自由填写；空白代表未审核。两个审核者使用独立存储键。\n"
        "任何预置空白均非人工判断；本工具不会自动生成标签。技术不可读保留题目并记录，不筛题。\n"
        "已生成缩略图最大512像素；如需原图核对，请由研究者单独提供中性命名原图并记录核对情况。\n")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True, help="Frozen audit.jsonl: exactly 100 independent recipes")
    parser.add_argument("--image-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    report = build_packet(args.manifest, args.image_root, args.output_dir)
    print(json.dumps({"output_dir": str(args.output_dir), **report}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
